import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFile(path.join(root,p),'utf8');
const runtime=await read('vendor/rainbow/rainbow.js');
const bridge=await read('native/runtime-bridge.js');
await mkdir(path.join(root,'native/generated'),{recursive:true});
await writeFile(path.join(root,'native/generated/runtime.js'),`// Generated by scripts/build-native.mjs.\nexport function createRuntime(host) {\nconst {System_in,System_out,System_err,System_fs}=host;\nconst System_getenvAsync0=(then)=>{then(null,{});return true;};\nconst System_getenvAsync1=(name,then)=>{then(null,null);return true;};\nconst System_exitAsync=(code,then)=>{then(new Error('Arc exit '+code));return true;};\n${runtime}\n${bridge}\n}\n`);
const files={};
for(const name of ['arc.arc','strings.arc','pprint.arc','code.arc','html.arc','srv.arc','app.arc','prompt.arc','news.arc']) files[name]=await read('upstream/'+name);
files['workers.arc']=await read('native/workers.arc');
await writeFile(path.join(root,'native/generated/sources.js'),'export default '+JSON.stringify(files)+';\n');
const assets={};
for(const name of ['arc.png','grayarrow.gif','graydown.gif','s.gif','robots.txt'])assets['/'+name]=(await readFile(path.join(root,'upstream/static',name))).toString('base64');
await writeFile(path.join(root,'native/generated/assets.js'),'export default '+JSON.stringify(assets)+';\n');
